import { db } from "./db";

/**
 * The workspace export, which is what "Export anytime" has to mean.
 *
 * The pricing FAQ, terms and privacy page all promise the buyer their data
 * leaves with them. Before this module the promise had no door: there was no
 * route, no button and no serializer. This builds one portable JSON document
 * from the workspace's own rows.
 *
 * Two rules decide the shape:
 *
 *   - **Content, not credentials.** Contacts, conversations, messages, score
 *     signals, drafts, members, pending invitations and webhook configuration
 *     are the workspace's data. Password digests, session tokens, API-key
 *     hashes, invitation token hashes, webhook signing secrets and Stripe ids
 *     are not — exporting them would turn a download into a credential leak.
 *   - **The workspace is the filter.** Every query is scoped by workspaceId
 *     (messages/signals/drafts through their thread relation), so a bug in the
 *     caller cannot turn one buyer's export into another's.
 *
 * The document is intentionally human-readable JSON. It is the portable copy a
 * buyer keeps, not a database backup: ids are preserved so threads, messages
 * and signals can be rejoined, and dates are ISO strings once serialized.
 */
export const EXPORT_FORMAT = "abetconnect.workspace";
export const EXPORT_VERSION = 1;

/**
 * The download's filename, kept pure so the header path can be proven without a
 * database. A workspace slug is generated by signup, but it is still user-facing
 * text: this collapses everything outside `[a-z0-9-]`, which removes quotes,
 * separators and CR/LF before the value can reach Content-Disposition.
 */
export function workspaceExportFilename(slug: string, takenAt: Date = new Date()): string {
  const safe =
    slug
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "") || "workspace";
  return `abetconnect-${safe}-${takenAt.toISOString().slice(0, 10)}.json`;
}

export async function buildWorkspaceExport(workspaceId: string, exportedAt: Date = new Date()) {
  const workspace = await db.workspace.findUnique({
    where: { id: workspaceId },
    select: {
      id: true,
      name: true,
      slug: true,
      sellsWhat: true,
      createdAt: true,
      updatedAt: true,
    },
  });
  if (!workspace) throw new Error("Workspace not found");

  const [members, invitations, contacts, threads, messages, signals, drafts, webhooks] =
    await Promise.all([
      db.membership.findMany({
        where: { workspaceId },
        orderBy: { createdAt: "asc" },
        select: {
          id: true,
          userId: true,
          role: true,
          createdAt: true,
          user: { select: { email: true, name: true, emailVerified: true } },
        },
      }),
      db.invite.findMany({
        where: { workspaceId },
        orderBy: { createdAt: "asc" },
        // tokenHash is deliberately absent: it is a live credential's digest,
        // not content the buyer needs to take with them.
        select: {
          id: true,
          email: true,
          role: true,
          createdById: true,
          createdAt: true,
          expiresAt: true,
          acceptedAt: true,
        },
      }),
      db.contact.findMany({
        where: { workspaceId },
        orderBy: { id: "asc" },
        select: {
          id: true,
          name: true,
          email: true,
          phone: true,
          company: true,
          title: true,
          seniority: true,
          avatarUrl: true,
          createdAt: true,
          updatedAt: true,
        },
      }),
      db.thread.findMany({
        where: { workspaceId },
        orderBy: { id: "asc" },
        select: {
          id: true,
          contactId: true,
          subject: true,
          channel: true,
          channels: true,
          score: true,
          bucket: true,
          scoreReason: true,
          intent: true,
          scoredBy: true,
          scoredAt: true,
          status: true,
          snoozedUntil: true,
          lastMessageAt: true,
          lastInboundAt: true,
          lastOutboundAt: true,
          awaitingReply: true,
          estimatedValueCents: true,
          currency: true,
          createdAt: true,
          updatedAt: true,
        },
      }),
      db.message.findMany({
        where: { thread: { workspaceId } },
        orderBy: { id: "asc" },
        select: {
          id: true,
          threadId: true,
          direction: true,
          channel: true,
          body: true,
          externalId: true,
          raw: true,
          sentAt: true,
          createdAt: true,
        },
      }),
      db.signal.findMany({
        where: { thread: { workspaceId } },
        orderBy: { id: "asc" },
        select: {
          id: true,
          threadId: true,
          kind: true,
          label: true,
          weight: true,
          evidence: true,
          createdAt: true,
        },
      }),
      db.draft.findMany({
        where: { thread: { workspaceId } },
        orderBy: { id: "asc" },
        select: {
          id: true,
          threadId: true,
          body: true,
          generatedBy: true,
          intent: true,
          status: true,
          sentAt: true,
          createdAt: true,
          updatedAt: true,
        },
      }),
      db.webhookEndpoint.findMany({
        where: { workspaceId },
        orderBy: { createdAt: "asc" },
        // The signing secret is a credential; the destination and event menu
        // are configuration the buyer can recognize in a new home.
        select: {
          id: true,
          url: true,
          events: true,
          active: true,
          createdAt: true,
        },
      }),
    ]);

  return {
    format: EXPORT_FORMAT,
    version: EXPORT_VERSION,
    exportedAt: exportedAt.toISOString(),
    workspace,
    counts: {
      members: members.length,
      invitations: invitations.length,
      contacts: contacts.length,
      threads: threads.length,
      messages: messages.length,
      signals: signals.length,
      drafts: drafts.length,
      webhooks: webhooks.length,
    },
    members,
    invitations,
    contacts,
    threads,
    messages,
    signals,
    drafts,
    webhooks,
  };
}

export type WorkspaceExport = Awaited<ReturnType<typeof buildWorkspaceExport>>;
